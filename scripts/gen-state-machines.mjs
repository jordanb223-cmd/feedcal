#!/usr/bin/env node
// Generates the TypeScript copy and the diagrams of the app's state machines from the database,
// which is their single source of truth (public.state_machines()). Run after any migration that
// changes them:  npm run db:states   (CI fails if the output is stale, like database types.)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const status = JSON.parse(execFileSync("npx", ["supabase", "status", "-o", "json"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }));
const apiUrl = status.API_URL;
const anon = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
if (!apiUrl || !anon) throw new Error("Local Supabase isn't running (npm run db:start).");

const res = await fetch(`${apiUrl}/rest/v1/rpc/state_machines`, {
  method: "POST",
  headers: { apikey: anon, authorization: `Bearer ${anon}`, "content-type": "application/json" },
  body: "{}",
});
if (!res.ok) throw new Error(`state_machines() failed: ${res.status}`);
const machines = await res.json();
const names = Object.keys(machines).sort();

// ---- TypeScript
const ts = `// GENERATED by \`npm run db:states\` from public.state_machines(). Do not edit by hand.
// The database enforces these moves (private.enforce_transition); see docs/STATE-MACHINES.md.
export const STATE_MACHINES = ${JSON.stringify(
  Object.fromEntries(names.map((n) => [n, { table: machines[n].table, column: machines[n].column, description: machines[n].description, transitions: machines[n].transitions.map(({ from, to }) => ({ from, to })) }])),
  null,
  2,
)} as const;
`;
writeFileSync(join(root, "packages/shared/src/state-machines.generated.ts"), ts);

// ---- Markdown diagrams (between the markers in docs/STATE-MACHINES.md)
const id = (s) => s.replace(/[^a-z0-9_]/gi, "_");
const block = names
  .map((n) => {
    const m = machines[n];
    const lines = m.transitions.map((t) => `  ${id(t.from)} --> ${id(t.to)}: ${t.description.replace(/[:;]/g, ",")}`);
    return [
      `### \`${n}\` — \`${m.table}.${m.column}\``,
      "",
      m.description,
      "",
      "```mermaid",
      "stateDiagram-v2",
      ...lines,
      "```",
      "",
      "| From | To | When |",
      "|---|---|---|",
      ...m.transitions.map((t) => `| \`${t.from}\` | \`${t.to}\` | ${t.description} |`),
      "",
    ].join("\n");
  })
  .join("\n");
const docPath = join(root, "docs/STATE-MACHINES.md");
const doc = readFileSync(docPath, "utf8");
const begin = "<!-- BEGIN GENERATED: npm run db:states -->";
const end = "<!-- END GENERATED -->";
const i = doc.indexOf(begin);
const j = doc.indexOf(end);
if (i < 0 || j < i) throw new Error("docs/STATE-MACHINES.md is missing the generated-section markers.");
writeFileSync(docPath, `${doc.slice(0, i + begin.length)}\n\n${block}\n${doc.slice(j)}`);
console.log(`state machines: ${names.length} (${names.join(", ")})`);
